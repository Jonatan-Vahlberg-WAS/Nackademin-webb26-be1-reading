const loans = [
    {
        id: 1, bookId: 3, userId: 2,
        loanDate: "2026-01-01",
        status: 'returned'
    },
    {
        id: 2, bookId: 1, userId: 1,
        loanDate: new Date().toISOString().split('T')[0],
        status: 'active'
    },
]

let nextId = 3;

/**
 * Get all loans
 * @returns {Array<Object>} - An array of loan objects
 */
export function getLoans() {
    return loans;
}

/**
 * create a new loan
 * @param {Object} loan - The loan object to create
 * @returns {Object} - The created loan object
 */
export function createLoan(loan) {
    const id = nextId++;
    // Add autogenerated fields to the loan object
    const newLoan = { id, status: 'active', loanDate: new Date().toISOString().split('T')[0], ...loan };
    // Add the new loan to the loans array
    loans.push(newLoan);
    // Return the new loan
    return newLoan;
}