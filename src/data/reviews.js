const reviews = []

let nextId = 1;

/**
 * Get all reviews for a book
 * @param {number} bookId - The ID of the book to get reviews for
 * @returns {Array<{
 *     id: number;
 *     bookId: number;
 *     userId: number;
 *     review: string;
 *     rating: number;
 *     createdAt: string;
 * }>} - An array of review objects or an empty array if no reviews are found
 */
export function getReviews(bookId) {
    return reviews.filter(review => review.bookId === bookId);
}

/**
 * Create a new review
 * @param {Object{
 *     id: number;
 *     bookId: number;
 *     userId: number;
 *     review: string;
 *     rating: number;
 *     createdAt: string;
 * }} review - The review object to create
 * @returns {Object} - The created review object
 */
export function createReview(review) {
    const id = nextId++;
    // Add autogenerated fields to the review object
    const newReview = { id, createdAt: new Date().toISOString(), ...review };
    // Add the new review to the reviews array
    reviews.push(newReview);
    // Return the new review
    return newReview;
}